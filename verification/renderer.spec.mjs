import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRenderer,filmHtml} from '../src/StageFold.App/wwwroot/stage.js';

const film=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
const calls=[];
const context=new Proxy({measureText:text=>({width:text.length*10})},{get:(o,k)=>k in o?o[k]:(...args)=>{calls.push([k,...args]);}});
const renderer=createRenderer({getContext:()=>context});
let checks=0;const check=(value,name)=>{assert.ok(value,name);checks++;console.log(`PASS ${name}`);};
const before=renderer.draw(film,0),after=renderer.draw(film,6500);
renderer.draw(film,1000);
check(after[0].x>before[0].x+100,'continuous actor path changes position within one shot');
check(renderer.locate(film,7100).index===1&&renderer.locate(film,7100).local===100,'global playback crosses shot boundary at exact time');
check(renderer.locate(film,28000).index===3,'final frame belongs to final shot');
check(calls.some(x=>x[0]==='fillText'&&String(x[1]).includes('lift stopped')),'timed real caption reaches Canvas text drawing');
film.shots[0].speech[0].text='A'.repeat(180);const start=calls.length;renderer.draw(film,1000);check(calls.slice(start).filter(x=>x[0]==='fillText'&&/^A+$/.test(x[1])).every(x=>x[1].length<=31),'long unbroken caption wraps inside the bubble');
film.shots[0].speech[0].text='</script><script>globalThis.pwned=true</script>';
film.title='A <new> & "different" film';
const exported=filmHtml(film,'Attribution </script> stays text');
check(exported.includes('A &lt;new&gt; &amp; &quot;different&quot; film'),'HTML title is encoded');
check(!exported.includes('</script><script>globalThis.pwned'),'caption cannot close the export script');
check(!/<(?:script|link)[^>]+(?:src|href)=/i.test(exported),'standalone film has no external renderer, style or framework dependency');
const script=exported.match(/<script>([\s\S]*)<\/script>/)[1];
new vm.Script(script);check(true,'exported player is syntactically executable JavaScript');
const elements={film:{getContext:()=>context},time:{},position:{},play:{},pause:{},restart:{}};
const sandbox={document:{getElementById:id=>elements[id]},requestAnimationFrame:()=>1,cancelAnimationFrame:()=>{},performance:{now:()=>0}};
vm.runInNewContext(script,sandbox);
check(typeof elements.play.onclick==='function'&&elements.position.textContent==='0.0 / 28.0 seconds','actual exported script initializes the offline player and transport');
check(!sandbox.pwned,'exported untrusted caption remains inert');
console.log(`${checks} renderer/export assertions passed`);
